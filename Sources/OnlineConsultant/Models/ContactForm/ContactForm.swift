import Foundation

/// SDK presentation state for a contact form shown in the chat UI.
///
/// The backend returns contact form field configuration in `config.contact_form` and
/// `actions[].contact_form`. The SDK combines that backend configuration with local UI state,
/// prefilled user data, action identifiers, and submit status so the form can be rendered and
/// retried without losing user input.
package struct ContactForm: Codable, Equatable, Sendable {

    /// Message text shown above the form fields.
    package let text: String?

    /// Message text shown after the form is successfully submitted.
    package let resultText: String?

    /// Placement strategy used by the SDK when showing the form.
    package let display: ContactFormDisplay

    /// Local form scenario used to route submit handling.
    package let kind: ContactFormKind

    /// Backend field configuration keyed by typed backend field key.
    package let fields: [ContactFormFieldKey: ContactFormField]

    /// User values used to prefill supported contact fields.
    package let prefill: ContactFormPrefill

    /// Last submitted values retained after a failed submit attempt.
    package let fieldValues: [String: String]

    /// Site action identifier used when the form was generated by an action.
    package let actionID: FlexibleID?

    /// Indicates that the form was successfully submitted and should be locked.
    package let isSubmitted: Bool

    /// Inline submit error message shown after a failed submit attempt.
    package let submitErrorMessage: String?

    private enum CodingKeys: String, CodingKey {
        case text
        case resultText
        case display
        case kind
        case fields
        case prefill
        case fieldValues
        case actionID
        case isSubmitted
        case submitErrorMessage
    }

    /// Creates contact form presentation state from backend configuration and local SDK state.
    package init(
        text: String? = nil,
        resultText: String? = nil,
        display: ContactFormDisplay = .afterFirstMessage,
        kind: ContactFormKind = .contact,
        fields: [ContactFormFieldKey: ContactFormField],
        prefill: ContactFormPrefill = ContactFormPrefill(),
        fieldValues: [String: String] = [:],
        actionID: FlexibleID? = nil,
        isSubmitted: Bool = false,
        submitErrorMessage: String? = nil
    ) {
        self.text = text
        self.resultText = resultText
        self.display = display
        self.kind = kind
        self.fields = fields
        self.prefill = prefill
        self.fieldValues = fieldValues
        self.actionID = actionID
        self.isSubmitted = isSubmitted
        self.submitErrorMessage = submitErrorMessage
    }

    package init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)

        text = try container.decodeIfPresent(String.self, forKey: .text)
        resultText = try container.decodeIfPresent(String.self, forKey: .resultText)
        display = try container.decodeIfPresent(
            ContactFormDisplay.self,
            forKey: .display
        ) ?? .afterFirstMessage
        kind = try container.decodeIfPresent(ContactFormKind.self, forKey: .kind) ?? .contact
        fields = try Dictionary(
            backendFields: container.decode([String: ContactFormField].self, forKey: .fields)
        )
        prefill = try container.decodeIfPresent(
            ContactFormPrefill.self,
            forKey: .prefill
        ) ?? ContactFormPrefill()
        fieldValues = try container.decodeIfPresent([String: String].self, forKey: .fieldValues) ?? [:]
        actionID = try container.decodeIfPresent(FlexibleID.self, forKey: .actionID)
        isSubmitted = try container.decodeIfPresent(Bool.self, forKey: .isSubmitted) ?? false
        submitErrorMessage = try container.decodeIfPresent(String.self, forKey: .submitErrorMessage)
    }

    package func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)

        try container.encodeIfPresent(text, forKey: .text)
        try container.encodeIfPresent(resultText, forKey: .resultText)
        try container.encode(display, forKey: .display)
        try container.encode(kind, forKey: .kind)
        try container.encode(fields.backendFields, forKey: .fields)
        try container.encode(prefill, forKey: .prefill)
        try container.encode(fieldValues, forKey: .fieldValues)
        try container.encodeIfPresent(actionID, forKey: .actionID)
        try container.encode(isSubmitted, forKey: .isSubmitted)
        try container.encodeIfPresent(submitErrorMessage, forKey: .submitErrorMessage)
    }
}

package extension ContactForm {

    /// Returns a copy marked as successfully submitted.
    func submitted() -> ContactForm {
        .init(
            text: text,
            resultText: resultText,
            display: display,
            kind: kind,
            fields: fields,
            prefill: prefill,
            fieldValues: fieldValues,
            actionID: actionID,
            isSubmitted: true,
            submitErrorMessage: nil
        )
    }

    /// Returns a copy with the inline submit error cleared.
    func clearingSubmitError() -> ContactForm {
        .init(
            text: text,
            resultText: resultText,
            display: display,
            kind: kind,
            fields: fields,
            prefill: prefill,
            fieldValues: fieldValues,
            actionID: actionID,
            isSubmitted: isSubmitted,
            submitErrorMessage: nil
        )
    }

    /// Returns a copy that preserves submitted values and shows an inline submit error.
    func applyingSubmitError(
        _ message: String,
        submittedFields: [String: String]
    ) -> ContactForm {
        .init(
            text: text,
            resultText: resultText,
            display: display,
            kind: kind,
            fields: fields,
            prefill: prefill,
            fieldValues: submittedFields,
            actionID: actionID,
            isSubmitted: false,
            submitErrorMessage: message
        )
    }
}
